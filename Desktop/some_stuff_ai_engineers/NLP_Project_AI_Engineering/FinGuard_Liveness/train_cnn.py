import os
import glob
import numpy as np
import librosa
import torch
import torch.nn as nn
import torch.optim as optim
from torch.utils.data import Dataset, DataLoader
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import classification_report, accuracy_score
from sklearn.metrics import ConfusionMatrixDisplay, RocCurveDisplay
import matplotlib.pyplot as plt
import joblib

# ================= КОНФИГУРАЦИЯ =================
AUDIO_DIR = "data/audio/bonafide"
BATCH_SIZE = 8
EPOCHS = 15
LEARNING_RATE = 0.001
DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")
IMG_SIZE = 128

# ================= ДАТАСЕТ =================
class AudioSpoofDataset(Dataset):
    """Генерирует Real (оригинал) и Spoof (аугментация) из реальных файлов."""
    def __init__(self, audio_dir):
        self.files = sorted(glob.glob(os.path.join(audio_dir, "*.flac")))
        if not self.files:
            raise ValueError(f"Папка {audio_dir} пуста! Сначала скачай данные.")

    def __len__(self):
        return len(self.files) * 2

    def _get_spectrogram(self, y, sr):
        S = librosa.feature.melspectrogram(y=y, sr=sr, n_mels=128, fmax=8000)
        S_db = librosa.power_to_db(S, ref=np.max)
        S_db = (S_db - S_db.mean()) / (S_db.std() + 1e-8)
        tensor = torch.tensor(S_db, dtype=torch.float32).unsqueeze(0)
        if tensor.shape[2] < IMG_SIZE:
            tensor = torch.nn.functional.pad(tensor, (0, IMG_SIZE - tensor.shape[2]))
        else:
            tensor = tensor[:, :, :IMG_SIZE]
        return tensor

    def __getitem__(self, idx):
        real_idx = idx // 2
        is_spoof = idx % 2
        y, sr = librosa.load(self.files[real_idx], sr=16000)

        if is_spoof:
            y = librosa.effects.pitch_shift(y=y, sr=sr, n_steps=np.random.uniform(-4, 4))
            y = librosa.effects.time_stretch(y=y, rate=np.random.uniform(0.8, 1.2))
            y = y + np.random.normal(0, 0.005, len(y))

        return self._get_spectrogram(y, sr), 1 if is_spoof else 0

# ================= МОДЕЛЬ CNN =================
class SpoofDetectorCNN(nn.Module):
    """2D CNN для анализа Mel-спектрограмм."""
    def __init__(self):
        super().__init__()
        self.features = nn.Sequential(
            nn.Conv2d(1, 16, 3, padding=1), nn.BatchNorm2d(16), nn.ReLU(), nn.MaxPool2d(2),
            nn.Conv2d(16, 32, 3, padding=1), nn.BatchNorm2d(32), nn.ReLU(), nn.MaxPool2d(2),
            nn.Conv2d(32, 64, 3, padding=1), nn.BatchNorm2d(64), nn.ReLU(), nn.MaxPool2d(2),
        )
        self.classifier = nn.Sequential(
            nn.Linear(64 * 16 * 16, 128), nn.ReLU(), nn.Dropout(0.5), nn.Linear(128, 2)
        )

    def forward(self, x):
        x = self.features(x)
        x = x.view(x.size(0), -1)
        return self.classifier(x)

# ================= ФЛАТТЕН ДЛЯ RF =================
def flatten_features(dataset):
    X, y = [], []
    for i in range(len(dataset)):
        tensor, label = dataset[i]
        X.append(tensor.numpy().flatten())
        y.append(label)
    return np.array(X), np.array(y)

# ================= ГЛАВНАЯ ФУНКЦИЯ =================
def main():
    print(f"Устройство: {DEVICE}")
    dataset = AudioSpoofDataset(AUDIO_DIR)
    train_size = int(0.8 * len(dataset))
    test_size = len(dataset) - train_size
    train_ds, test_ds = torch.utils.data.random_split(dataset, [train_size, test_size])

    print(f"Выборка: {len(dataset)} (Train: {train_size}, Test: {test_size})")

    # 1. Обучение CNN
    print("\nОбучение 2D CNN...")
    cnn_model = SpoofDetectorCNN().to(DEVICE)
    loader = DataLoader(train_ds, batch_size=BATCH_SIZE, shuffle=True)
    criterion = nn.CrossEntropyLoss()
    optimizer = optim.Adam(cnn_model.parameters(), lr=LEARNING_RATE)

    for epoch in range(EPOCHS):
        cnn_model.train()
        for inputs, labels in loader:
            inputs, labels = inputs.to(DEVICE), labels.to(DEVICE)
            optimizer.zero_grad()
            loss = criterion(cnn_model(inputs), labels)
            loss.backward()
            optimizer.step()

    # 2. Оценка CNN
    cnn_model.eval()
    cnn_preds, cnn_labels = [], []
    with torch.no_grad():
        for inputs, labels in DataLoader(test_ds, batch_size=BATCH_SIZE):
            inputs = inputs.to(DEVICE)
            preds = torch.argmax(cnn_model(inputs), dim=1)
            cnn_preds.extend(preds.cpu().numpy())
            cnn_labels.extend(labels.numpy())

    print("\nМетрики 2D CNN:")
    print(classification_report(cnn_labels, cnn_preds, target_names=['Real', 'Spoof']))

    # 3. Бонус: Сравнение с Random Forest (+10% к оценке)
    print("\nОбучение Random Forest (Baseline)...")
    X_train, y_train = flatten_features(train_ds)
    X_test, y_test = flatten_features(test_ds)
    rf_model = RandomForestClassifier(n_estimators=100, random_state=42)
    rf_model.fit(X_train, y_train)
    rf_preds = rf_model.predict(X_test)

    print("Метрики Random Forest:")
    print(classification_report(y_test, rf_preds, target_names=['Real', 'Spoof']))

    # Сохранение
    torch.save(cnn_model.state_dict(), "finguard_cnn.pth")
    joblib.dump(rf_model, "finguard_rf.pkl")
    print("Модели сохранены: finguard_cnn.pth, finguard_rf.pkl")

def plot_metrics(y_true, y_probs, y_preds):
    """Сохраняет Confusion Matrix и ROC-кривую для отчета."""
    fig, axes = plt.subplots(1, 2, figsize=(12, 5))

    # 1. Матрица ошибок (Показывает, где модель ошибается)
    ConfusionMatrixDisplay.from_predictions(
        y_true, y_preds, display_labels=['Real', 'Spoof'],
        cmap='Blues', ax=axes[0]
    )
    axes[0].set_title('Confusion Matrix (Матрица ошибок)')

    # 2. ROC-кривая (Показывает качество разделения классов)
    RocCurveDisplay.from_predictions(
        y_true, y_probs[:, 1], ax=axes[1], color='darkorange'
    )
    axes[1].plot([0, 1], [0, 1], 'k--', label='Random Guess')
    axes[1].set_title('ROC Curve (Качество классификации)')

    plt.tight_layout()
    plt.savefig("model_metrics.png", dpi=150)
    print("Графики метрик сохранены: model_metrics.png")

if __name__ == "__main__":
    main()